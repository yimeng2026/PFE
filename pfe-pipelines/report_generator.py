#!/usr/bin/env python3
"""
PFE Report Generator
====================

Generates Markdown/HTML reports from Lean verification pipeline results.
Part of PFE Phase 2: Pipeline expansion (report generation pipeline).
"""

import json
import os
import sys
from datetime import datetime
from pathlib import Path
from typing import Dict, List, Optional


class PFEReportGenerator:
    """Generates formatted reports from PFE pipeline results."""
    
    def __init__(self, output_dir: str = "reports"):
        self.output_dir = Path(output_dir)
        self.output_dir.mkdir(parents=True, exist_ok=True)
        
    def generate_lean_report(self, pipeline_results: Dict) -> str:
        """Generate Markdown report from Lean parser results."""
        timestamp = datetime.now().isoformat()
        
        report = f"""# PFE Lean Text Scan Report

**Generated:** {timestamp}
**Pipeline Version:** v4.8
**Status:** Text-only static scan (not Lean compilation)

---

## Input-Reported Summary

| Metric | Value |
|--------|-------|
| Total Files Parsed | {pipeline_results.get('total_files', 0)} |
| Total Theorems | {pipeline_results.get('total_theorems', 0)} |
| Total Lemmas | {pipeline_results.get('total_lemmas', 0)} |
| Total Definitions | {pipeline_results.get('total_definitions', 0)} |
| Total Axioms | {pipeline_results.get('total_axioms', 0)} |
| Total Sorry Tokens in Code | {pipeline_results.get('total_sorry', 0)} |
| Reported Zero-Sorry Count (not proof) | {pipeline_results.get('proven_count', 0)} |
| Reported Try-Block Count | {pipeline_results.get('try_block_count', 0)} |

---

## Sorry Distribution by File

"""
        
        for file_name, stats in pipeline_results.get('file_stats', {}).items():
            report += f"### {file_name}\n\n"
            report += f"- **Theorems:** {stats.get('theorems', 0)}\n"
            report += f"- **Lemmas:** {stats.get('lemmas', 0)}\n"
            report += f"- **Definitions:** {stats.get('definitions', 0)}\n"
            report += f"- **Axioms:** {stats.get('axioms', 0)}\n"
            report += f"- **Sorry:** {stats.get('sorry', 0)}\n"
            report += f"- **Try-Blocks:** {stats.get('try_blocks', 0)}\n\n"
            
            if stats.get('sorry_list'):
                report += "**Sorry Locations:**\n\n"
                for line, context in stats['sorry_list']:
                    report += f"- Line {line}: `{context[:80]}...`\n"
                report += "\n"
        
        report += """---

## Scope and Limits

- This report formats the supplied pipeline result; it does not independently reproduce the input.
- Text scanning is not Lean compilation. Zero `sorry` tokens does not establish soundness, completeness or proof status.
- Numerical agreement, parameter fitting and LLM commentary are not independent mathematical or physical proof.
- Historical theorem and physics claims must be checked against their own versioned source, executable verification and axiom dependencies; none are inferred here.

*Report generated by PFE Report Generator v1.1; text-scan scope only.*
"""
        
        return report
    
    def save_report(self, report: str, filename: str = "lean_verification_report.md") -> str:
        """Save report to output directory."""
        filepath = self.output_dir / filename
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(report)
        return str(filepath)
    
    def generate_html_report(self, pipeline_results: Dict) -> str:
        """Generate an escaped HTML preview of the text-scan report."""
        from html import escape

        md_report = self.generate_lean_report(pipeline_results)
        html = f"""<!DOCTYPE html>
<html>
<head>
<meta charset="UTF-8">
<title>PFE Lean Text Scan Report</title>
<style>
body {{ font-family: 'Segoe UI', Arial, sans-serif; max-width: 900px; margin: 0 auto; padding: 20px; }}
h1 {{ color: #2c3e50; border-bottom: 3px solid #3498db; padding-bottom: 10px; }}
h2 {{ color: #34495e; border-left: 4px solid #3498db; padding-left: 15px; margin-top: 30px; }}
h3 {{ color: #7f8c8d; }}
table {{ border-collapse: collapse; width: 100%; margin: 15px 0; }}
th, td {{ border: 1px solid #ddd; padding: 8px; text-align: left; }}
th {{ background: #f5f5f5; font-weight: bold; }}
tr:nth-child(even) {{ background: #fafafa; }}
code {{ background: #f0f0f0; padding: 2px 5px; border-radius: 3px; font-family: 'Consolas', monospace; }}
blockquote {{ border-left: 3px solid #3498db; padding: 10px 15px; background: #f8f9fa; margin: 15px 0; }}
</style>
</head>
<body>
<pre>{escape(md_report)}</pre>
</body>
</html>"""
        return html


